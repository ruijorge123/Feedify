#!/usr/bin/env node
/**
 * Scans frontend/public and writes src/lib/portfolioManifest.js.
 *
 * The portfolio used to be a hand-maintained array, which meant most of the
 * work sat on disk unpublished. CRA can't read the filesystem at runtime, so
 * the listing is baked at build time instead: drop new images into /public and
 * re-run this (`yarn portfolio`) — nothing else needs editing.
 */
const fs = require("fs");
const path = require("path");

const PUBLIC = path.join(__dirname, "..", "public");
const OUT = path.join(__dirname, "..", "src", "lib", "portfolioManifest.js");

const IMG = /\.(webp|jpe?g|png)$/i;

// Icons, verification files and internal assets are not portfolio work.
const SKIP_FILES = new Set([
  "apple-touch-icon.png", "icon-192.png", "icon-512.png",
  "icon-512-maskable.png", "icon_512x512.png",
  // Landing-page-only assets: the before/after slider pair and its result set.
  "freese-before.webp", "freese-after.webp",
  "before.webp", "after2.webp", "after3.webp", "after4.webp", "after5.webp",
]);
const SKIP_DIRS = new Set(["datapenting", "testimonihalamanawal"]);

/** "skincare-serum10.webp" -> "Skincare Serum" */
function titleOf(file) {
  return file
    .replace(IMG, "")
    .replace(/[-_]+/g, " ")
    .replace(/\d+/g, "")
    .trim()
    .replace(/\s+/g, " ")
    .replace(/\b\w/g, (c) => c.toUpperCase()) || "Karya";
}

function listImages(dir) {
  return fs.readdirSync(dir)
    .filter((f) => IMG.test(f) && !SKIP_FILES.has(f))
    .sort();
}

const items = [];
const seen = new Set(); // the same shot exists in both / and /gallery; publish it once

function push(type, cat, images, title) {
  const key = images.join("|");
  if (seen.has(key)) return;
  seen.add(key);
  items.push({ type, cat, title, images });
}

// ── single images ───────────────────────────────────────────────────────────
const SINGLE_SOURCES = [
  { dir: "studio", type: "studio", cat: "Foto Studio" },
  { dir: "marketplace", type: "marketplace", cat: "Etalase Marketplace" },
  { dir: "gallery/marketplace", type: "marketplace", cat: "Etalase Marketplace" },
  { dir: "gallery/skincare", type: "feed", cat: "Skincare" },
  { dir: "gallery/fnb", type: "feed", cat: "Makanan & Minuman" },
  { dir: "gallery/fashion", type: "feed", cat: "Fashion" },
  { dir: "gallery/parfum", type: "feed", cat: "Parfum" },
  { dir: "", type: "feed", cat: "Konten Feed" },
];

for (const { dir, type, cat } of SINGLE_SOURCES) {
  const abs = path.join(PUBLIC, dir);
  if (!fs.existsSync(abs)) continue;
  for (const f of listImages(abs)) {
    const url = "/" + (dir ? `${dir}/` : "") + f;
    push(type, cat, [url], titleOf(f));
  }
}

// ── carousel sets ───────────────────────────────────────────────────────────
const carouselDir = path.join(PUBLIC, "carousel");
if (fs.existsSync(carouselDir)) {
  for (const folder of fs.readdirSync(carouselDir).sort()) {
    const abs = path.join(carouselDir, folder);
    if (!fs.statSync(abs).isDirectory() || SKIP_DIRS.has(folder)) continue;
    // Slides are named 1,2,3… — sort numerically so the story stays in order.
    const slides = listImages(abs)
      .sort((a, b) => parseInt(a, 10) - parseInt(b, 10))
      .map((f) => `/carousel/${folder}/${f}`);
    if (!slides.length) continue;
    const name = folder.replace(/\s*\d*\s*slides?$/i, "").trim();
    push("carousel", `Carousel ${slides.length} Slide`, slides, titleOf(name));
  }
}

const body = `// GENERATED by scripts/build-portfolio.js — do not edit by hand.
// Add images to /public and run \`yarn portfolio\` to refresh.
const WORKS = ${JSON.stringify(items, null, 2)};

export default WORKS;
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body, "utf-8");

const byType = items.reduce((a, i) => ({ ...a, [i.type]: (a[i.type] || 0) + 1 }), {});
const photos = items.reduce((n, i) => n + i.images.length, 0);
console.log(`portofolio: ${items.length} karya / ${photos} foto`, byType);
